; PPA-1 ASM - Moskau (Dschinghis Khan), MIDI adaptation.
; Original user-supplied MIDI reduced to four oscillator voices.
; Uses includes/ppa-sound.inc (SLOT 1, bank 2000).
; Starting CPU speed: approx. 100 kHz. Tune by ear.
; Data table at EEPROM 0000:1000, relative to Y pointer.
.org $0000
    JMP start
.include "includes/ppa-sound.inc"

start:
    CALL sound_init
    MOV Y-HI,#10
    MOV Y-LO,#00

song_loop:
    MOV BR-HI,#00
    CALL next_byte
    MOV B,A
    CALL next_byte
    MOV C,A
    CMP C,#FF
    JZ finish
    CALL sound_voice1

    MOV BR-HI,#00
    CALL next_byte
    MOV B,A
    CALL next_byte
    MOV C,A
    CALL sound_voice2

    MOV BR-HI,#00
    CALL next_byte
    MOV B,A
    CALL next_byte
    MOV C,A
    CALL sound_voice3

    MOV BR-HI,#00
    CALL next_byte
    MOV B,A
    CALL next_byte
    MOV C,A
    CALL sound_voice4

    ; Step duration approximately 96 MIDI ticks at 100 kHz.
    MOV B,#0E
wait_outer:
    MOV C,#64
wait_inner:
    DEC C
    JNZ wait_inner
    DEC B
    JNZ wait_outer
    JMP song_loop

next_byte:
    LD A,Y
    INC Y-LO
    JNZ no_carry
    INC Y-HI
no_carry:
    RET

finish:
    CALL sound_stop
    HLT

